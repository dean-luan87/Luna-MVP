#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Verify Midplatform TTS Runtime Planning v1."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from capabilities.governance.midplatform_module_definition_template_v1 import (
    TEMPLATE_ID,
    TEMPLATE_SECTIONS,
    validate_module_definition,
)
from capabilities.governance.midplatform_tts_runtime_planning_v1 import (
    AUDIO_ARTIFACT_CANDIDATE_FIELDS,
    AUDIO_PLAYBACK_BOUNDARY_RULES,
    AUDIO_SYNTHESIS_BOUNDARY_RULES,
    AUTHORIZATION_REQUIREMENTS,
    BOUNDARY_FALSE,
    BOUNDARY_MATRIX_FALSE,
    BOUNDARY_TRUE,
    CACHE_ARTIFACT_BOUNDARY_RULES,
    CORE_CHAIN_BOUNDARY,
    CURRENT_PREFERRED_PROVIDER_CANDIDATE,
    FAILURE_ROUTE_MAPPINGS,
    FINAL_DECISION_GO,
    FOUR_LAYER_ARCHITECTURE,
    HARNESS_ID,
    NEXT_PHASE_GO,
    NON_CLAIMS,
    NO_RAW_CONSTITUTION_RULES,
    PHASE_ID,
    PROVIDER_ABSTRACTION_RULES,
    PROVIDER_READINESS_RULES,
    PROVIDER_SWITCH_BOUNDARY_RULES,
    SCOPE,
    SPEECH_GATE_NON_BYPASS_RULES,
    SPEECH_REQUEST_INTAKE_FIELDS,
    TRACEABILITY_REQUIREMENTS,
    TTS_RUNTIME_LAYER_POSITIONING,
    UPSTREAM_ROADMAP_FINAL,
    UPSTREAM_ROADMAP_NEXT,
    VOICE_MODEL_BOUNDARY_RULES,
    VOICE_PROFILE_BOUNDARY_RULES,
)
from capabilities.governance.midplatform_tts_runtime_roadmap_decision_v1 import (
    SELECTED_ROUTE,
)

MIN_CHECKS = 327

REQUIRED = (
    "tts_runtime_planning_policy_v1.json",
    "tts_runtime_roadmap_input_review_v1.json",
    "tts_runtime_module_definition_v1.json",
    "speech_request_candidate_intake_contract_v1.json",
    "tts_runtime_output_contract_v1.json",
    "tts_provider_abstraction_plan_v1.json",
    "current_tts_provider_candidate_register_v1.json",
    "provider_switch_boundary_plan_v1.json",
    "tts_provider_readiness_plan_v1.json",
    "tts_voice_model_boundary_plan_v1.json",
    "tts_voice_profile_personalization_boundary_plan_v1.json",
    "tts_audio_synthesis_boundary_plan_v1.json",
    "tts_audio_output_playback_boundary_plan_v1.json",
    "tts_cache_and_artifact_boundary_plan_v1.json",
    "tts_authorization_requirement_plan_v1.json",
    "tts_failure_route_plan_v1.json",
    "tts_traceability_audit_plan_v1.json",
    "tts_no_raw_constitution_policy_v1.json",
    "tts_speech_gate_non_bypass_policy_v1.json",
    "tts_runtime_boundary_matrix_v1.json",
    "tts_runtime_dryrun_plan_v1.json",
    "non_claims_register_v1.json",
    "tts_runtime_planning_decision_v1.json",
    "summary.json",
    "verifier_report.json",
)


def _load(path: Path) -> Dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--output-root",
        default="/Users/luanlei/Desktop/Luna-Workspace-Min/_tmp_eval_out/midplatform_tts_runtime_planning",
    )
    p.add_argument(
        "--roadmap-decision-root",
        default="/Users/luanlei/Desktop/Luna-Workspace-Min/_tmp_eval_out/midplatform_tts_runtime_roadmap_decision",
    )
    args = p.parse_args()
    root = Path(args.output_root)
    roadmap_root = Path(args.roadmap_decision_root)
    checks: List[Dict[str, Any]] = []

    def ok(cid: str, passed: bool) -> None:
        checks.append({"check_id": cid, "passed": bool(passed)})

    for f in REQUIRED:
        if f == "verifier_report.json":
            # This file is generated by this verifier; check after write.
            continue
        ok(f"file.{f}", (root / f).is_file())

    roadmap_vr = _load(roadmap_root / "verifier_report.json")
    roadmap_sm = _load(roadmap_root / "summary.json")

    summary = _load(root / "summary.json")
    policy = _load(root / "tts_runtime_planning_policy_v1.json")
    input_review = _load(root / "tts_runtime_roadmap_input_review_v1.json")
    module_def = _load(root / "tts_runtime_module_definition_v1.json")
    intake = _load(root / "speech_request_candidate_intake_contract_v1.json")
    output_contract = _load(root / "tts_runtime_output_contract_v1.json")
    provider_abstraction = _load(root / "tts_provider_abstraction_plan_v1.json")
    provider_register = _load(root / "current_tts_provider_candidate_register_v1.json")
    provider_switch = _load(root / "provider_switch_boundary_plan_v1.json")
    provider = _load(root / "tts_provider_readiness_plan_v1.json")
    voice_model = _load(root / "tts_voice_model_boundary_plan_v1.json")
    voice_profile = _load(root / "tts_voice_profile_personalization_boundary_plan_v1.json")
    synthesis = _load(root / "tts_audio_synthesis_boundary_plan_v1.json")
    playback = _load(root / "tts_audio_output_playback_boundary_plan_v1.json")
    cache = _load(root / "tts_cache_and_artifact_boundary_plan_v1.json")
    auth = _load(root / "tts_authorization_requirement_plan_v1.json")
    failure = _load(root / "tts_failure_route_plan_v1.json")
    trace = _load(root / "tts_traceability_audit_plan_v1.json")
    no_raw = _load(root / "tts_no_raw_constitution_policy_v1.json")
    non_bypass = _load(root / "tts_speech_gate_non_bypass_policy_v1.json")
    boundary = _load(root / "tts_runtime_boundary_matrix_v1.json")
    dryrun = _load(root / "tts_runtime_dryrun_plan_v1.json")
    decision = _load(root / "tts_runtime_planning_decision_v1.json")

    ok("upstream.roadmap_go", roadmap_vr.get("verifier") == "GO")
    ok("upstream.roadmap_final", roadmap_sm.get("final_decision") == UPSTREAM_ROADMAP_FINAL)
    ok("upstream.roadmap_next", roadmap_sm.get("recommended_next_phase") == UPSTREAM_ROADMAP_NEXT)
    ok("upstream.route_a", roadmap_sm.get("selected_route") == SELECTED_ROUTE)

    ok("summary.phase", summary.get("phase") == PHASE_ID)
    ok("summary.scope", summary.get("scope") == SCOPE)
    ok("summary.planning_only", summary.get("tts_runtime_planning_only") is True)
    ok("summary.pass", summary.get("planning_pass") is True)
    ok("summary.final", summary.get("final_decision") == FINAL_DECISION_GO)
    ok("summary.next", summary.get("recommended_next_phase") == NEXT_PHASE_GO)
    ok("summary.boundary", summary.get("core_chain_boundary") == CORE_CHAIN_BOUNDARY)
    ok("summary.harness", summary.get("controlled_provider_readiness_harness_ref") == HARNESS_ID)

    for field in BOUNDARY_TRUE:
        ok(f"true.{field}", summary.get(field) is True)
    for field in BOUNDARY_FALSE:
        ok(f"false.{field}", summary.get(field) is False)

    ok("policy.execution_runtime", policy.get("tts_runtime_is_execution_runtime_not_enforcement") is True)
    ok("policy.speech_req_only", policy.get("speech_request_candidate_only_not_raw_clauses") is True)
    ok("policy.harness_later", policy.get("controlled_provider_readiness_harness_required_later") is True)
    ok("policy.non_bypass", policy.get("speech_gate_non_bypass_required") is True)
    ok("policy.four_layer", policy.get("four_layer_architecture") == FOUR_LAYER_ARCHITECTURE)
    for pos in TTS_RUNTIME_LAYER_POSITIONING:
        ok(f"policy.pos.{pos[:18]}", pos in (policy.get("tts_runtime_layer_positioning") or []))

    ok("input.pass", input_review.get("review_pass") is True)
    ok("input.route", input_review.get("selected_route") == SELECTED_ROUTE)
    ok("input.request_exists", input_review.get("speech_request_candidate_exists") is True)
    ok("input.not_tts", input_review.get("speech_request_not_tts") is True)
    ok("input.tts_blocked", input_review.get("direct_tts_route_blocked") is True)
    ok("input.harness", input_review.get("harness_post_review_go") is True)

    identity = module_def.get("module_identity") or {}
    processing = module_def.get("processing_scope") or {}
    runtime = module_def.get("runtime_boundaries") or {}
    valid, issues = validate_module_definition(module_def)
    ok("module.valid", valid and len(issues) == 0)
    ok("module.id", identity.get("module_id") == "midplatform_tts_runtime_v1")
    ok("module.type", identity.get("module_type") == "midplatform_voice_synthesis_runtime_module")
    ok(
        "module.role",
        identity.get("role") == "speech_request_candidate_to_audio_artifact_runtime_planning",
    )
    ok("module.layer", identity.get("system_layer") == "Output")
    ok("module.arch_layer", identity.get("architectural_layer") == "ExecutionRuntime")
    ok("module.runtime_abstraction", identity.get("runtime_abstraction") is True)
    ok("module.provider_abstraction", identity.get("provider_abstraction_required") is True)
    ok(
        "module.no_provider_logic_core",
        identity.get("provider_specific_logic_forbidden_in_runtime_core") is True,
    )
    ok(
        "module.current_pref_candidate",
        identity.get("current_preferred_provider_candidate") == CURRENT_PREFERRED_PROVIDER_CANDIDATE,
    )
    ok("module.no_provider_selected_exec_now", identity.get("provider_selected_for_execution_now") is False)
    ok("module.no_write", processing.get("write_allowed") is False)
    ok("module.runtime_off", runtime.get("runtime_enabled_now") is False)

    upstream_mods = (module_def.get("upstream_sources") or {}).get("upstream_modules") or []
    ok("module.up_voice", "midplatform_voice_output_plane_v1" in upstream_mods)

    downstream_mods = (module_def.get("downstream_targets") or {}).get("downstream_modules") or []
    ok("module.down_audio", "audio_output_later" in downstream_mods)

    output_c = module_def.get("output_contract") or {}
    ok("module.audio_artifact", output_c.get("output_object_type") == "audio_artifact_candidate")

    for section in TEMPLATE_SECTIONS:
        ok(f"section.{section[:12]}", section in module_def)

    ok("intake.fields17", len(intake.get("required_fields") or []) == 17)
    ok("intake.speech_only", intake.get("consumes_speech_request_candidate_only") is True)
    ok("intake.no_raw", intake.get("raw_constitution_clause_binding_forbidden") is True)
    ok("intake.no_bypass", intake.get("speech_gate_bypass_forbidden") is True)
    for field in SPEECH_REQUEST_INTAKE_FIELDS:
        ok(f"intake.{field[:15]}", field in (intake.get("required_fields") or []))

    ok("output.fields19", len(output_contract.get("required_fields") or []) == 19)
    ok("output.not_synth", output_contract.get("not_synthesis_or_playback") is True)
    o_defaults = output_contract.get("defaults") or {}
    ok("output.no_audio", o_defaults.get("audio_output_allowed") is False)
    ok("output.no_play", o_defaults.get("playback_allowed") is False)
    for field in AUDIO_ARTIFACT_CANDIDATE_FIELDS:
        ok(f"output.{field[:15]}", field in (output_contract.get("required_fields") or []))

    ok("pabs.count8", provider_abstraction.get("rule_count") == 8)
    ok(
        "pabs.current_pref",
        provider_abstraction.get("current_preferred_provider_candidate")
        == CURRENT_PREFERRED_PROVIDER_CANDIDATE,
    )
    for rule in PROVIDER_ABSTRACTION_RULES:
        ok(f"pabs.{rule[:18]}", rule in (provider_abstraction.get("rules") or []))

    ok("preg.current_pref", provider_register.get("current_preferred_provider_candidate") == CURRENT_PREFERRED_PROVIDER_CANDIDATE)
    candidates = provider_register.get("provider_candidates") or []
    ok("preg.has_qianwen", any(x.get("provider_candidate_id") == "qianwen_tts_candidate" for x in candidates))
    q = next((x for x in candidates if x.get("provider_candidate_id") == "qianwen_tts_candidate"), {}) or {}
    ok("preg.q.type", q.get("provider_type") == "external_or_cloud_tts_provider")
    ok("preg.q.usage", q.get("current_project_usage") == "current_preferred_candidate")
    ok("preg.q.no_exec", q.get("provider_selected_for_execution_now") is False)
    ok("preg.q.no_import", q.get("provider_imported_now") is False)
    ok("preg.q.no_net", q.get("network_call_executed_now") is False)
    ok("preg.q.no_voice_model", q.get("voice_model_selected_now") is False)
    ok("preg.q.no_audio", q.get("audio_generated_now") is False)

    ok("pswitch.count7", provider_switch.get("rule_count") == 7)
    ok("pswitch.no_auto_now", provider_switch.get("provider_auto_switch_executed_now") is False)
    ok("pswitch.no_selected_exec_now", provider_switch.get("provider_selected_for_execution_now") is False)
    for rule in PROVIDER_SWITCH_BOUNDARY_RULES:
        ok(f"pswitch.{rule[:18]}", rule in (provider_switch.get("rules") or []))

    ok("provider.count10", provider.get("rule_count") == 10)
    ok("provider.harness", provider.get("controlled_provider_readiness_harness_ref") == HARNESS_ID)
    for rule in PROVIDER_READINESS_RULES:
        ok(f"provider.{rule[:18]}", rule in (provider.get("rules") or []))

    ok("vmodel.count6", voice_model.get("rule_count") == 6)
    for rule in VOICE_MODEL_BOUNDARY_RULES:
        ok(f"vmodel.{rule[:18]}", rule in (voice_model.get("rules") or []))

    ok("vprofile.count7", voice_profile.get("rule_count") == 7)
    for rule in VOICE_PROFILE_BOUNDARY_RULES:
        ok(f"vprofile.{rule[:18]}", rule in (voice_profile.get("rules") or []))

    ok("synth.count6", synthesis.get("rule_count") == 6)
    for rule in AUDIO_SYNTHESIS_BOUNDARY_RULES:
        ok(f"synth.{rule[:18]}", rule in (synthesis.get("rules") or []))

    ok("playback.count6", playback.get("rule_count") == 6)
    for rule in AUDIO_PLAYBACK_BOUNDARY_RULES:
        ok(f"playback.{rule[:18]}", rule in (playback.get("rules") or []))

    ok("cache.count6", cache.get("rule_count") == 6)
    for rule in CACHE_ARTIFACT_BOUNDARY_RULES:
        ok(f"cache.{rule[:18]}", rule in (cache.get("rules") or []))

    ok("auth.count9", auth.get("requirement_count") == 9)
    for req in AUTHORIZATION_REQUIREMENTS:
        ok(f"auth.{req[:18]}", req in (auth.get("requirements") or []))

    ok("failure.count8", failure.get("route_count") == 8)
    for m in FAILURE_ROUTE_MAPPINGS:
        ok(
            f"failure.{m['condition'][:16]}",
            any(
                x.get("condition") == m["condition"] and x.get("route") == m["route"]
                for x in (failure.get("routes") or [])
            ),
        )

    ok("trace.count9", trace.get("requirement_count") == 9)
    for req in TRACEABILITY_REQUIREMENTS:
        ok(f"trace.{req[:18]}", req in (trace.get("requirements") or []))

    ok("no_raw.count5", no_raw.get("rule_count") == 5)
    ok("no_raw.speech_only", no_raw.get("consumes_speech_request_candidate_only") is True)
    for rule in NO_RAW_CONSTITUTION_RULES:
        ok(f"noraw.{rule[:18]}", rule in (no_raw.get("rules") or []))

    ok("bypass.count6", non_bypass.get("rule_count") == 6)
    ok("bypass.forbidden", non_bypass.get("speech_gate_bypass_forbidden") is True)
    for rule in SPEECH_GATE_NON_BYPASS_RULES:
        ok(f"bypass.{rule[:18]}", rule in (non_bypass.get("rules") or []))

    ok("boundary.all_false", boundary.get("all_runtime_actions_false") is True)
    for field in BOUNDARY_MATRIX_FALSE:
        ok(f"matrix.{field[:18]}", boundary.get("matrix", {}).get(field) is False)

    ok("dryrun.next", dryrun.get("next_phase") == NEXT_PHASE_GO)

    ok("decision.pass", decision.get("planning_pass") is True)
    ok("decision.final", decision.get("final_decision") == FINAL_DECISION_GO)
    ok("decision.four_layer", decision.get("four_layer_architecture") == FOUR_LAYER_ARCHITECTURE)
    ok("decision.chain3", len(decision.get("main_chain_defined") or []) == 3)
    ok("decision.layer_pos", len(decision.get("tts_runtime_layer_positioning") or []) >= 5)

    ok("template_id", summary.get("template_id") == TEMPLATE_ID)
    ok("non_claims", len(_load(root / "non_claims_register_v1.json").get("non_claims") or []) >= len(NON_CLAIMS))
    for claim in NON_CLAIMS:
        ok(f"claim.{claim[:18]}", claim in (_load(root / "non_claims_register_v1.json").get("non_claims") or []))

    passed = sum(1 for c in checks if c["passed"])
    total = len(checks)
    pass_all = summary.get("planning_pass") is True
    go = passed >= MIN_CHECKS and pass_all and passed == total

    report = {
        "phase": PHASE_ID,
        "verifier": "GO" if go else "NO_GO",
        "checks_passed": passed,
        "checks_total": total,
        "min_checks_required": MIN_CHECKS,
        "planning_pass": pass_all,
        "final_decision": summary.get("final_decision"),
        "recommended_next_phase": summary.get("recommended_next_phase"),
        "checks": checks,
    }
    (root / "verifier_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    ok("file.verifier_report.json", (root / "verifier_report.json").is_file())
    print(json.dumps({"verifier": report["verifier"], "checks_passed": passed, "checks_total": total}, ensure_ascii=False))
    return 0 if go else 1


if __name__ == "__main__":
    raise SystemExit(main())
