def build_condition_rules_for_policy(
    policy_id: str, evaluation_rule_ids: Iterable[str]
) -> Tuple[ConditionRule, ...]:
    rules: List[ConditionRule] = []
    for idx, rule_id in enumerate(evaluation_rule_ids, start=1):
        if rule_id not in _RULE_TEMPLATE:
            rules.append(
                ConditionRule(
                    rule_id=rule_id,
                    policy_id=policy_id,
                    condition_type="version_snapshot_condition",
                    operator="exists",
                    expected_value=None,
                    input_path="evaluation_contract_version",
                    required=True,
                    blocking=True,
                    rejection_reason="missing_version_snapshot",
                    evaluation_order=idx,
                    short_circuit_allowed=True,
                    trace_required=True,
                )
            )
            continue

        tpl = _RULE_TEMPLATE[rule_id]
        rules.append(
            ConditionRule(
                rule_id=rule_id,
                policy_id=policy_id,
                condition_type=str(tpl[0]),
                operator=str(tpl[1]),
                expected_value=tpl[2],
                input_path=str(tpl[3]),
                required=bool(tpl[4]),
                blocking=bool(tpl[5]),
                rejection_reason=str(tpl[6]),
                evaluation_order=int(tpl[7]),
                short_circuit_allowed=True,
                trace_required=True,
            )
        )
    return tuple(rules)
